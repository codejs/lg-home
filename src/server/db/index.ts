/**
 * The SQLite database. Nothing is opened on import: the server, the add_user
 * CLI and the tests call openDatabase() with the path they want (see
 * config.ts for DATABASE_PATH), then runMigrations().
 *
 * `db` is a live binding: modules that import it see the database once it is
 * open. Using it before that throws a clear error.
 */
import { mkdirSync } from "node:fs";
import { dirname } from "node:path";
import Database from "better-sqlite3";
import { drizzle, type BetterSQLite3Database } from "drizzle-orm/better-sqlite3";
import { migrate } from "drizzle-orm/better-sqlite3/migrator";
import * as schema from "./schema.js";

export type Db = BetterSQLite3Database<typeof schema>;

/** Stands in for `db` until openDatabase() is called. */
const notOpen = new Proxy({} as Db, {
  get() {
    throw new Error("The database is not open: call openDatabase() first");
  },
});

export let db: Db = notOpen;
let sqlite: Database.Database | null = null;

/**
 * Open (creating if needed) the database at `path` and make it `db`. Any
 * database opened before is closed first. ":memory:" gives a private one.
 */
export function openDatabase(path: string): Db {
  closeDatabase();
  if (path !== ":memory:") mkdirSync(dirname(path), { recursive: true });
  sqlite = new Database(path);
  sqlite.pragma("journal_mode = WAL");
  sqlite.pragma("foreign_keys = ON");
  db = drizzle(sqlite, { schema });
  return db;
}

/** Close the database, if open; `db` throws again until the next openDatabase(). */
export function closeDatabase(): void {
  sqlite?.close();
  sqlite = null;
  db = notOpen;
}

export function isDatabaseOpen(): boolean {
  return sqlite !== null;
}

/** Apply any pending migrations from ./drizzle (generated by `npm run db:generate`). */
export function runMigrations() {
  migrate(db, { migrationsFolder: "drizzle" });
}

export { schema };
